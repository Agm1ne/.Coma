    res = vkCreateDevice_fn(g_vk_phys, &dci, NULL, &g_vk_dev);
    if (res != VK_SUCCESS) { vkDestroyInstance_fn(g_vk_inst, NULL); return 0; }

    vkGetDeviceQueue_fn = (PFN_vkGetDeviceQueue)vkGetDevProcAddr_fn(g_vk_dev, "vkGetDeviceQueue");
