    cpci2.stage.pName = "main";
    cpci2.layout = g_vk_layout;
    vkCreateComputePipelines_fn(g_vk_dev, VK_NULL_HANDLE, 1, &cpci2, NULL, &g_vk_pipe);

    VkDescriptorPoolSize poolSizes[2] = {0};
